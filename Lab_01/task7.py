print("Task 7 — Comparisons and Boolean Logic")

age = 22
is_master_student = True

print(f"age >= 18:                          {age >= 18}")            # True
print(f"age < 30:                           {age < 30}")             # True
print(f"age == 22:                          {age == 22}")            # True
print(f"age != 25:                          {age != 25}")            # True
print(f"age >= 18 and is_master_student:    {age >= 18 and is_master_student}")   # True
print(f"age < 18 or is_master_student:      {age < 18 or is_master_student}")     # True
print(f"not is_master_student:              {not is_master_student}")             # False

print()