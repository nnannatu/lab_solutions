print("Task 8 — Python Collections")

# list  -> ordered, mutable, allows duplicates
programming_languages = ["Python", "JavaScript", "Rust"]

# tuple -> ordered, immutable
numbers = (10, 20, 30)

# set   -> unordered, unique elements only
cities = {"Novosibirsk", "Moscow", "Kazan"}

# dict  -> key/value pairs
student = {
    "name": "Anna",
    "age": 22,
    "university": "NSU",
}

print(programming_languages)
print(numbers)
print(cities)
print(student)

print(type(programming_languages))
print(type(numbers))
print(type(cities))
print(type(student))

print()