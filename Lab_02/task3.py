print("Task 3 — Assignment and Augmented Assignment")

# Starting balance.
balance = 1000.0

# += adds to the existing value.
# Equivalent to: balance = balance + 250
balance += 250

# -= subtracts from the existing value.
# Equivalent to: balance = balance - 120
balance -= 120

# *= multiplies the existing value.
# Equivalent to: balance = balance * 1.05
balance *= 1.05

# :.2f formats the float with exactly 2 decimal places.
print(f"Final balance: {balance:.2f}")

print()
