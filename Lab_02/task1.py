print("Task 1 — Built-in Functions")

values = [12, 7, 19, 5, 14]

count = len(values)
smallest = min(values)
largest = max(values)
total = sum(values)
mean = total / count

print(f"Count:    {count}")
print(f"Smallest: {smallest}")
print(f"Largest:  {largest}")
print(f"Total:    {total}")
print(f"Mean:     {mean}")

print()
